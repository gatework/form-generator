import { test, expect } from '@playwright/test'

test('all controls render and a required field validates before submitting', async({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()) })
  await page.goto('/')
  for (const button of await page.locator('.palette button').all()) await button.click()
  await expect(page.locator('.builder-field')).toHaveCount(21)
  await page.locator('.field-select').first().click()
  await page.getByRole('textbox', { name: '标题', exact: true }).fill('Account')
  await page.getByRole('switch', { name: '必填', exact: true }).click()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  const modal = page.locator('.arco-modal')
  await modal.getByRole('button', { name: '提交', exact: true }).click()
  await expect(modal.locator('.arco-form-item-message').first()).toContainText('Account')
  await expect(modal.locator('pre')).toHaveCount(0)
  await modal.locator('input').first().fill('Ada')
  await modal.getByRole('button', { name: '提交', exact: true }).click()
  await expect(modal.locator('pre')).toContainText('Ada')
  await modal.getByRole('button', { name: '重置', exact: true }).click()
  await expect(modal.locator('input').first()).toHaveValue('')
  await page.locator('.arco-modal-close-btn').click()
  await expect(modal).toHaveCount(0)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 Vue 文件', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('GeneratedForm.vue')
  await page.reload()
  await expect(page.locator('.builder-field')).toHaveCount(21)
  expect(errors).toEqual([])
})

test('duplicates independently, reorders, imports atomically and restores the draft', async({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '单行文本', exact: true }).dragTo(page.locator('.canvas'))
  await expect(page.locator('.builder-field')).toHaveCount(1)
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await page.getByRole('textbox', { name: '标题', exact: true }).fill('Copied')
  await expect(page.locator('.field-select').first()).toContainText('单行文本')
  await page.locator('.field-select').last().dragTo(page.locator('.builder-field').first())
  await expect(page.locator('.field-select').first()).toContainText('Copied')
  const json = await page.evaluate(() => localStorage.getItem('gatework:form-generator:arco:v1')!)
  await page.getByRole('button', { name: '清空', exact: true }).click()
  await page.locator('.arco-modal').getByRole('button', { name: '应用', exact: true }).click()
  await expect(page.locator('.builder-field')).toHaveCount(0)
  await page.getByRole('button', { name: '导入 JSON', exact: true }).click()
  await page.locator('.arco-modal textarea').fill(json)
  await page.locator('.arco-modal').getByRole('button', { name: '应用', exact: true }).click()
  await page.locator('.arco-modal').last().getByRole('button', { name: '应用', exact: true }).click()
  await expect(page.locator('.builder-field')).toHaveCount(2)
  await page.reload()
  await expect(page.locator('.field-select').first()).toContainText('Copied')
  await page.getByRole('button', { name: '导入 JSON', exact: true }).click()
  await page.locator('.arco-modal textarea').fill('{"fields":[]}')
  await page.locator('.arco-modal').getByRole('button', { name: '应用', exact: true }).click()
  await expect(page.locator('.arco-message')).toContainText('导入失败')
  await expect(page.locator('.builder-field')).toHaveCount(2)
})

test('upload selection stays local and binds file-list in preview', async({ page }) => {
  const posts: string[] = []
  page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()) })
  await page.goto('/')
  await page.getByRole('button', { name: '上传', exact: true }).click()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  const modal = page.locator('.arco-modal')
  await modal.locator('input[type=file]').setInputFiles({ name: 'sample.txt', mimeType: 'text/plain', buffer: Buffer.from('sample') })
  await expect(modal.locator('.arco-upload-list')).toContainText('sample.txt')
  await modal.getByRole('button', { name: '提交', exact: true }).click()
  await expect(modal.locator('pre')).toContainText('sample.txt')
  expect(posts).toEqual([])
})

test('appearance changes preserve edits, reject other origins and fit a narrow screen', async({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '单行文本', exact: true }).click()
  await page.getByRole('textbox', { name: '标题', exact: true }).fill('Unsaved label')
  await page.evaluate(() => window.dispatchEvent(new MessageEvent('message', { origin: 'https://other.example', source: window, data: { type: 'form-generator:appearance', locale: 'en-US', dark: true } })))
  await expect(page.getByRole('button', { name: '运行', exact: true })).toBeVisible()
  await page.evaluate(() => window.postMessage({ type: 'form-generator:appearance', locale: 'en-US', dark: true }, location.origin))
  await expect(page.getByRole('button', { name: 'Preview', exact: true })).toBeVisible()
  await expect(page.locator('body')).toHaveAttribute('arco-theme', 'dark')
  await expect(page.getByRole('textbox', { name: 'Label', exact: true })).toHaveValue('Unsaved label')
  await page.screenshot({ path: 'test-results/designer-dark.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/designer-mobile.png', fullPage: true })
})

for (const width of [390, 768]) {
  test(`compact workspace supports add, edit, preview and draft recovery at ${width}px`, async({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/')
    const navigation = page.getByRole('navigation', { name: '设计工作区' })
    await expect(page.locator('.canvas')).toBeVisible()
    await expect(page.locator('.palette')).toBeHidden()
    await navigation.getByRole('button', { name: '组件', exact: true }).click()
    await page.locator('.palette').getByRole('button', { name: '单行文本', exact: true }).click()
    await expect(navigation.getByRole('button', { name: '画布', exact: true })).toBeFocused()
    await page.locator('.field-select').click()
    await expect(page.locator('.canvas')).toBeHidden()
    await expect(navigation.getByRole('button', { name: '属性', exact: true })).toBeFocused()
    await page.getByRole('textbox', { name: '标题', exact: true }).fill('移动端申请人')
    await navigation.getByRole('button', { name: '画布', exact: true }).click()
    await expect(page.locator('.field-select')).toHaveText('移动端申请人')
    await page.getByRole('button', { name: '运行', exact: true }).click()
    const modal = page.locator('.arco-modal')
    await modal.getByRole('textbox', { name: '移动端申请人', exact: true }).fill('Ada')
    await modal.getByRole('button', { name: '提交', exact: true }).click()
    await expect(modal.locator('pre')).toContainText('Ada')
    await page.locator('.arco-modal-close-btn').click()
    await page.reload()
    await expect(page.locator('.field-select')).toHaveText('移动端申请人')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight)).toBe(true)
    await page.screenshot({ path: `test-results/designer-compact-${width}.png`, animations: 'disabled' })
  })
}
