import { test, expect } from '@playwright/test'

test('rich text formats, links, resets, changes appearance and reloads without CDN requests', async({ page }) => {
  const remote: string[] = []
  const errors: string[] = []
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (['http:', 'https:'].includes(url.protocol) && url.hostname !== '127.0.0.1') {
      remote.push(url.href)
      return route.abort()
    }
    return route.continue()
  })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: '富文本', exact: true }).click()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  const modal = page.locator('.arco-modal')
  const area = modal.frameLocator('.rich-text iframe').locator('body')
  await expect(area).toBeEditable()
  await area.fill('Offline rich text')
  await area.press('ControlOrMeta+a')
  await modal.getByRole('button', { name: '粗体', exact: true }).click()
  await expect(area.locator('strong')).toHaveText('Offline rich text')
  await area.press('ControlOrMeta+k')
  const dialog = page.getByRole('dialog', { name: '插入/编辑链接' })
  await dialog.getByRole('combobox', { name: '地址', exact: true }).fill('https://example.com/docs')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(area.locator('a')).toHaveAttribute('href', 'https://example.com/docs')
  await area.press('ControlOrMeta+z')
  await expect(area.locator('a')).toHaveCount(0)
  await area.press('ControlOrMeta+Shift+z')
  await expect(area.locator('a')).toHaveAttribute('href', 'https://example.com/docs')
  await modal.getByRole('button', { name: '提交', exact: true }).click()
  await expect(modal.locator('pre')).toContainText('<strong>')
  await expect(modal.locator('pre')).toContainText('https://example.com/docs')
  await page.evaluate(() => window.postMessage({ type: 'form-generator:appearance', locale: 'en-US', dark: true }, location.origin))
  await expect(modal.getByRole('button', { name: 'Bold', exact: true })).toBeVisible()
  await expect(area.locator('strong')).toHaveText('Offline rich text')
  const surface = await modal.locator('.preview-viewport').evaluate(element => getComputedStyle(element).backgroundColor)
  await expect(area).toHaveCSS('background-color', surface)
  await expect(modal.locator('.tox-menubar')).toHaveCSS('background-color', surface)
  await modal.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(area).toHaveText('')
  await page.locator('.arco-modal-close-btn').click()
  await expect(modal).toHaveCount(0)
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(modal.frameLocator('.rich-text iframe').locator('body')).toBeEditable()
  expect(remote).toEqual([])
  expect(errors).toEqual([])
})
